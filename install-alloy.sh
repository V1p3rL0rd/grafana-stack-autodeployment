#!/usr/bin/env bash
###############################################################################
# install-alloy.sh
#
# Installs Grafana Alloy as a hardened systemd service on a client host and
# ships its logs to the central Loki. Replaces Promtail (end-of-life since
# March 2026).
#
# Collected (same labels as the old Promtail setup, so queries keep working):
#   /var/log/*.log (except auth.log)  -> {job="varlogs",          host=<hostname>}
#   /var/log/auth.log                 -> {job="auth",             host=<hostname>}
#   systemd journal                   -> {job="systemd-journal",  host=<hostname>, unit, level}
#
# Usage:
#   sudo ./install-alloy.sh --loki-url http://<LOKI_IP>:3100/loki/api/v1/push \
#        [--version X.Y.Z] [--disable-promtail]
#
#   --loki-url          Loki push endpoint (required).
#   --version           Alloy version (default 1.21.2).
#   --disable-promtail  Stop and disable an existing promtail.service.
#
# Idempotent: re-running skips the download when the version matches and
# restarts Alloy only when its config or unit changed.
###############################################################################

set -Eeuo pipefail

VERSION="1.21.2"
LOKI_URL=""
DISABLE_PROMTAIL=false
BIN="/usr/local/bin/alloy"
CONF_DIR="/etc/alloy"
CONF="${CONF_DIR}/config.alloy"
DATA_DIR="/var/lib/alloy"
UNIT="/etc/systemd/system/alloy.service"
SVC_USER="alloy"
UI_ADDR="127.0.0.1:12345"

log()  { echo "[INFO]  $*"; }
warn() { echo "[WARN]  $*" >&2; }
die()  { echo "[ERROR] $*" >&2; exit 1; }
trap 'die "failed at line ${LINENO}: ${BASH_COMMAND}"' ERR

usage() { sed -n '2,26p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

while [[ $# -gt 0 ]]; do
    case "$1" in
        --loki-url)         LOKI_URL="${2:?--loki-url needs a value}"; shift 2 ;;
        --version)          VERSION="${2:?--version needs a value}"; shift 2 ;;
        --disable-promtail) DISABLE_PROMTAIL=true; shift ;;
        -h|--help)          usage 0 ;;
        *)                  warn "Unknown argument: $1"; usage 1 ;;
    esac
done

[[ $EUID -eq 0 ]] || die "Run as root: sudo $0 --loki-url ..."
[[ -n "${LOKI_URL}" ]] || { warn "--loki-url is required"; usage 1; }
[[ "${LOKI_URL}" =~ ^https?://[^/[:space:]\"]+/loki/api/v1/push$ ]] \
    || die "--loki-url must look like http://10.0.0.5:3100/loki/api/v1/push"
[[ "${VERSION}" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "Invalid --version '${VERSION}'"

case "$(uname -m)" in
    x86_64)  ARCH=amd64 ;;
    aarch64) ARCH=arm64 ;;
    *)       die "Unsupported architecture: $(uname -m)" ;;
esac

for tool in curl unzip; do
    if ! command -v "${tool}" &>/dev/null; then
        log "Installing ${tool}..."
        DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${tool}" >/dev/null
    fi
done

# --- 1. service user: may read logs (adm) and the journal, nothing else -------
if ! id "${SVC_USER}" &>/dev/null; then
    useradd --system --no-create-home --home-dir "${DATA_DIR}" --shell /usr/sbin/nologin "${SVC_USER}"
    log "Created system user ${SVC_USER}"
fi
for grp in adm systemd-journal; do
    getent group "${grp}" &>/dev/null && usermod -aG "${grp}" "${SVC_USER}"
done
install -d -m 0755 -o root -g root "${CONF_DIR}"
install -d -m 0750 -o "${SVC_USER}" -g "${SVC_USER}" "${DATA_DIR}"

# --- 2. binary (download + SHA256 verification) -------------------------------
installed="$("${BIN}" --version 2>/dev/null | awk 'NR == 1 {print $3}' | sed 's/^v//' || true)"
changed=false
if [[ "${installed}" == "${VERSION}" ]]; then
    log "Alloy ${VERSION} already installed, skipping download."
else
    tmp="$(mktemp -d)"
    trap 'rm -rf "${tmp}"' EXIT
    name="alloy-linux-${ARCH}.zip"
    base="https://github.com/grafana/alloy/releases/download/v${VERSION}"
    log "Downloading Alloy ${VERSION} (${name})..."
    curl -fsSL --retry 3 -o "${tmp}/${name}" "${base}/${name}"
    curl -fsSL --retry 3 -o "${tmp}/SHA256SUMS" "${base}/SHA256SUMS"
    (cd "${tmp}" && grep " ${name}\$" SHA256SUMS | sha256sum -c --quiet -) \
        || die "SHA256 verification failed for ${name}"
    unzip -q -o "${tmp}/${name}" -d "${tmp}"
    install -m 0755 -o root -g root "${tmp}/alloy-linux-${ARCH}" "${BIN}"
    log "Installed Alloy ${VERSION} (was: ${installed:-none})"
    changed=true
fi

# --- 3. pipeline config -------------------------------------------------------
new_conf="$(mktemp)"
cat > "${new_conf}" <<EOF
// Generated by install-alloy.sh — re-run the script to change it.
logging {
  level = "warn"
}

// /var/log/*.log except auth.log  ->  job="varlogs"
local.file_match "varlogs" {
  path_targets = [{
    __path__         = "/var/log/*.log",
    __path_exclude__ = "/var/log/auth.log",
    job              = "varlogs",
    host             = constants.hostname,
  }]
}

// auth.log  ->  job="auth"
local.file_match "auth" {
  path_targets = [{
    __path__ = "/var/log/auth.log",
    job      = "auth",
    host     = constants.hostname,
  }]
}

loki.source.file "files" {
  targets       = array.concat(local.file_match.varlogs.targets, local.file_match.auth.targets)
  forward_to    = [loki.write.central.receiver]
  // Without a stored position start at the end of the file instead of
  // re-sending its whole history (matters when migrating from Promtail).
  tail_from_end = true
}

loki.relabel "journal" {
  forward_to = []

  rule {
    source_labels = ["__journal__systemd_unit"]
    target_label  = "unit"
  }
  rule {
    source_labels = ["__journal_priority_keyword"]
    target_label  = "level"
  }
}

loki.source.journal "journal" {
  max_age       = "12h"
  relabel_rules = loki.relabel.journal.rules
  labels        = {
    job  = "systemd-journal",
    host = constants.hostname,
  }
  forward_to    = [loki.write.central.receiver]
}

loki.write "central" {
  endpoint {
    url = "${LOKI_URL}"
  }
}
EOF

"${BIN}" fmt "${new_conf}" >/dev/null || { rm -f "${new_conf}"; die "Generated Alloy config failed validation (alloy fmt)."; }
if ! cmp -s "${new_conf}" "${CONF}"; then
    install -m 0644 -o root -g root "${new_conf}" "${CONF}"
    log "Config written: ${CONF}"
    changed=true
fi
rm -f "${new_conf}"

# --- 4. hardened systemd unit -------------------------------------------------
unit_content="[Unit]
Description=Grafana Alloy (log shipping to Loki)
Documentation=https://grafana.com/docs/alloy/latest/
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
User=${SVC_USER}
Group=${SVC_USER}
SupplementaryGroups=adm systemd-journal
ExecStart=${BIN} run --storage.path=${DATA_DIR}/data --server.http.listen-addr=${UI_ADDR} --disable-reporting ${CONF}
Restart=on-failure
RestartSec=5s

NoNewPrivileges=yes
ProtectSystem=strict
ReadWritePaths=${DATA_DIR}
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictNamespaces=yes
LockPersonality=yes
CapabilityBoundingSet=

[Install]
WantedBy=multi-user.target
"
if [[ ! -f "${UNIT}" ]] || ! diff -q <(printf '%s' "${unit_content}") "${UNIT}" &>/dev/null; then
    printf '%s' "${unit_content}" > "${UNIT}"
    systemctl daemon-reload
    log "Unit file written: ${UNIT}"
    changed=true
fi

# --- 5. Promtail migration ----------------------------------------------------
if systemctl is-active --quiet promtail 2>/dev/null; then
    if [[ "${DISABLE_PROMTAIL}" == "true" ]]; then
        systemctl disable --now promtail
        log "Promtail stopped and disabled."
    else
        warn "promtail.service is still running: logs will be shipped twice. Re-run with --disable-promtail."
    fi
fi

# --- 6. (re)start and verify --------------------------------------------------
systemctl enable alloy >/dev/null 2>&1
if [[ "${changed}" == "true" ]] || ! systemctl is-active --quiet alloy; then
    systemctl restart alloy
fi

for _ in $(seq 1 20); do
    if curl -fsS --max-time 2 "http://${UI_ADDR}/-/ready" -o /dev/null 2>/dev/null; then
        log "Alloy is running. Pipeline status: http://${UI_ADDR} (local only; use ssh -L 12345:${UI_ADDR} to view)."
        log "Verify in Grafana Explore: {host=\"$(hostname)\"}"
        exit 0
    fi
    sleep 1
done
systemctl status alloy --no-pager || true
die "Alloy did not become ready. Check: journalctl -u alloy -n 50"
