#!/usr/bin/env bash
###############################################################################
# backup-observability.sh
#
# Backs up / restores the state of the observability stack that cannot be
# regenerated:
#   config.tar.gz            /opt/observability (incl. .env, secrets, TLS cert,
#                            your alert.rules.yml and dashboards)
#   grafana_data.tar.gz      Grafana DB: users, dashboards made in the UI,
#                            alert rules, API keys
#   silences.json            active Alertmanager silences (exported via API —
#                            the on-disk snapshot lags up to 15 minutes)
#
# Prometheus data is NOT included (large, time-limited by retention,
# and regenerated by scraping). Snapshot that volume at the storage layer
# (LVM/ZFS/VM snapshot) if you need them.
#
# Usage:
#   sudo ./backup-observability.sh [--dest DIR] [--keep N]
#   sudo ./backup-observability.sh --restore DIR [--yes]
#
#   --dest     Where backups go (default /var/backups/observability).
#   --keep     How many backups to keep (default 7). Older ones are removed.
#   --restore  Restore from a backup directory created by this script.
#   --yes      Do not ask for confirmation before restoring.
#
# Cron example (daily 02:30):
#   30 2 * * * root /opt/observability-scripts/backup-observability.sh --keep 14 >> /var/log/observability-backup.log 2>&1
#
# Grafana is paused (not stopped) for the second or two the archive takes so
# its SQLite DB is copied consistently. Docker reports it "unhealthy" until the
# next healthcheck (<= 10 s) after that — expected.
###############################################################################

set -Eeuo pipefail

BASE_DIR="${OBS_BASE_DIR:-/opt/observability}"
PROJECT="observability"
DEST="/var/backups/observability"
KEEP=7
RESTORE_DIR=""
ASSUME_YES=false
VOLUMES=(grafana_data)
PAUSE_SERVICES=(grafana)
AM_URL="http://localhost:9093"

log()  { echo "[$(date '+%F %T')] [INFO]  $*"; }
warn() { echo "[$(date '+%F %T')] [WARN]  $*" >&2; }
die()  { echo "[$(date '+%F %T')] [ERROR] $*" >&2; exit 1; }
trap 'die "failed at line ${LINENO}: ${BASH_COMMAND}"' ERR

usage() { sed -n '2,32p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

while [[ $# -gt 0 ]]; do
    case "$1" in
        --dest)    DEST="${2:?--dest needs a value}"; shift 2 ;;
        --keep)    KEEP="${2:?--keep needs a value}"; shift 2 ;;
        --restore) RESTORE_DIR="${2:?--restore needs a value}"; shift 2 ;;
        --yes|-y)  ASSUME_YES=true; shift ;;
        -h|--help) usage 0 ;;
        *)         warn "Unknown argument: $1"; usage 1 ;;
    esac
done

[[ $EUID -eq 0 ]] || die "Run as root: sudo $0"
[[ "${KEEP}" =~ ^[1-9][0-9]*$ ]] || die "--keep must be a positive integer"
[[ -f "${BASE_DIR}/docker-compose.yml" ]] || die "${BASE_DIR}/docker-compose.yml not found — is the stack deployed?"

compose() { docker compose --project-directory "${BASE_DIR}" -f "${BASE_DIR}/docker-compose.yml" "$@"; }

# Any image of the stack that ships busybox tar; Prometheus' is always present.
HELPER_IMAGE="$(compose config --images 2>/dev/null | grep -m1 '/prometheus:' || true)"
[[ -n "${HELPER_IMAGE}" ]] || die "Cannot determine the Prometheus image from docker-compose.yml"
helper() { docker run --rm --network none --user 0 --entrypoint sh "$@"; }

PAUSED=()
unpause_all() {
    local svc
    for svc in "${PAUSED[@]}"; do compose unpause "${svc}" >/dev/null 2>&1 || true; done
    PAUSED=()
}

# ----------------------------------------------------------------------------
backup() {
    local ts dir vol svc
    ts="$(date -u +%Y%m%dT%H%M%SZ)"
    dir="${DEST}/obs-${ts}"
    install -d -m 0700 "${DEST}" "${dir}"
    log "Backing up to ${dir}"

    # Configs (contains .env with secrets -> directory is 0700, files 0600).
    tar -C "$(dirname "${BASE_DIR}")" -czf "${dir}/config.tar.gz" "$(basename "${BASE_DIR}")"

    trap 'unpause_all; die "failed at line ${LINENO}: ${BASH_COMMAND}"' ERR
    trap 'unpause_all' EXIT
    for svc in "${PAUSE_SERVICES[@]}"; do
        if [[ "$(docker inspect -f '{{.State.Running}}' "${svc}" 2>/dev/null)" == "true" ]]; then
            compose pause "${svc}" >/dev/null && PAUSED+=("${svc}")
        fi
    done
    for vol in "${VOLUMES[@]}"; do
        docker volume inspect "${PROJECT}_${vol}" &>/dev/null || { warn "Volume ${PROJECT}_${vol} not found, skipped"; continue; }
        helper -v "${PROJECT}_${vol}:/data:ro" -v "${dir}:/backup" "${HELPER_IMAGE}" \
            -c "tar -C /data -czf /backup/${vol}.tar.gz ."
    done
    unpause_all
    trap 'die "failed at line ${LINENO}: ${BASH_COMMAND}"' ERR
    trap - EXIT

    # Silences through the API: always current, unlike the periodic disk snapshot.
    if [[ "$(docker inspect -f '{{.State.Running}}' alertmanager 2>/dev/null)" == "true" ]]; then
        compose exec -T alertmanager amtool silence query -o json --alertmanager.url="${AM_URL}" \
            > "${dir}/silences.json"
        local n_sil
        n_sil="$( (grep -o '"id"' "${dir}/silences.json" || true) | wc -l)"
        log "Exported ${n_sil} active silence(s)."
    else
        warn "alertmanager is not running: silences not exported"
    fi

    {
        echo "created_utc=${ts}"
        echo "host=$(hostname)"
        echo "base_dir=${BASE_DIR}"
        compose config --images | sed 's/^/image=/'
    } > "${dir}/MANIFEST"
    (cd "${dir}" && sha256sum ./*.tar.gz ./*.json 2>/dev/null > SHA256SUMS || true)
    [[ -s "${dir}/SHA256SUMS" ]] || die "Could not checksum the backup"
    chmod 0600 "${dir}"/*

    # Integrity check of what was just written.
    for f in "${dir}"/*.tar.gz; do gzip -t "${f}" || die "Corrupt archive: ${f}"; done
    log "Backup complete: $(du -sh "${dir}" | cut -f1) in ${dir}"

    # Rotation: keep the newest KEEP backups.
    local old
    mapfile -t old < <(find "${DEST}" -mindepth 1 -maxdepth 1 -type d -name 'obs-[0-9]*T[0-9]*Z' | sort -r | tail -n +"$((KEEP + 1))")
    for f in "${old[@]}"; do
        rm -rf -- "${f}"
        log "Removed old backup ${f}"
    done
}

# ----------------------------------------------------------------------------
err_restore() {
    echo "[$(date '+%F %T')] [ERROR] restore failed at line $1: $2" >&2
    echo "The stack is STOPPED. Previous config: $3" >&2
    echo "To go back:  rm -rf ${BASE_DIR} && cp -a $3 ${BASE_DIR} && cd ${BASE_DIR} && docker compose up -d" >&2
    exit 1
}

restore() {
    local dir="${RESTORE_DIR%/}" vol
    [[ -f "${dir}/config.tar.gz" && -f "${dir}/SHA256SUMS" ]] || die "${dir} is not a backup created by this script"
    (cd "${dir}" && sha256sum -c --quiet SHA256SUMS) || die "Checksum verification failed for ${dir}"

    if [[ "${ASSUME_YES}" != "true" ]]; then
        read -r -p "Restore ${dir} over ${BASE_DIR}? The stack will be stopped and current Grafana/Alertmanager data replaced. [y/N] " ans
        [[ "${ans}" =~ ^[Yy]$ ]] || die "Aborted."
    fi

    log "Stopping the stack (volumes are kept)..."
    compose down

    # Keep the current config next to the restore, just in case.
    local keep
    keep="${BASE_DIR}.pre-restore-$(date -u +%Y%m%dT%H%M%SZ)"
    cp -a "${BASE_DIR}" "${keep}"
    log "Current config saved to ${keep}"
    # From here on the stack is down: on any failure tell the operator how to get back.
    trap 'err_restore "${LINENO}" "${BASH_COMMAND}" "${keep}"' ERR
    tar -C "$(dirname "${BASE_DIR}")" -xzf "${dir}/config.tar.gz"

    for vol in "${VOLUMES[@]}"; do
        [[ -f "${dir}/${vol}.tar.gz" ]] || { warn "${vol}.tar.gz not in backup, skipped"; continue; }
        log "Restoring volume ${PROJECT}_${vol}..."
        docker volume create "${PROJECT}_${vol}" >/dev/null
        helper -v "${PROJECT}_${vol}:/data" -v "${dir}:/backup:ro" "${HELPER_IMAGE}" \
            -c "rm -rf /data/* /data/.[!.]* /data/..?* && tar -C /data -xzpf /backup/${vol}.tar.gz"
    done

    log "Starting the stack..."
    compose up -d --wait --wait-timeout 240 || die "Stack did not become healthy after restore. Check: cd ${BASE_DIR} && docker compose ps"

    if [[ -s "${dir}/silences.json" && "$(tr -d '[:space:]' < "${dir}/silences.json")" != "[]" ]]; then
        compose exec -T alertmanager amtool silence import --alertmanager.url="${AM_URL}" \
            < "${dir}/silences.json" >/dev/null
        log "Imported silences from backup."
    fi
    log "Restore complete. Run the deploy script once to re-apply configs for this host if it differs from the original."
}

if [[ -n "${RESTORE_DIR}" ]]; then restore; else backup; fi
